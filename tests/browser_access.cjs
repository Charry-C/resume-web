/* UI walkthrough against an explicitly configured local server. Creates one demo resume. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');

(async () => {
  const base = process.env.BASE_URL || 'http://localhost:8765';
  const password = process.env.ADMIN_PASSWORD;
  if (!password) throw new Error('Set ADMIN_PASSWORD to the test server administrator password');
  const output = process.env.SCREENSHOT_DIR || '/tmp/resume-access-shots';
  fs.mkdirSync(output, { recursive: true });
  const chrome = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
  const browser = await chromium.launch(fs.existsSync(chrome) ? { executablePath: chrome } : {});
  const errors = [];
  let did;
  const adminContext = await browser.newContext({ viewport: { width: 1480, height: 940 } });
  const guestContext = await browser.newContext({ viewport: { width: 1480, height: 940 }, hasTouch: true });
  const admin = await adminContext.newPage();
  const guest = await guestContext.newPage();
  admin.on('pageerror', error => errors.push(error.message));
  guest.on('pageerror', error => errors.push(error.message));
  try {
    await admin.goto(base);
    await admin.locator('#unlockForm').waitFor();
    await admin.screenshot({ animations: 'disabled', path: path.join(output, 'guest-entrance.png') });
    assert.equal(await admin.locator('#drop').count(), 0);
    await admin.getByRole('button', { name: '管理员登录', exact: true }).click();
    await admin.locator('#adminPassword').fill(password);
    await admin.locator('#loginForm button[type=submit]').click();
    await admin.locator('#drop').waitFor();
    await admin.screenshot({ animations: 'disabled', path: path.join(output, 'admin-workspace-empty.png') });
    await admin.locator('#demoBtn').click();
    await admin.locator('.a4 .f').first().waitFor({ timeout: 30000 });
    did = new URL(admin.url()).hash.split('/').at(-1);
    assert(await admin.locator('[contenteditable=true]').count() > 0);
    assert.equal(await admin.locator('#exportBtn').count(), 0);
    // Add a real selection-anchored annotation through the UI.
    await admin.locator('.f[data-path="sections.0.items.0.bullets.0"]').evaluate(el => {
      el.focus();
      const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
      const node = walker.nextNode();
      const range = document.createRange(); range.setStart(node, 0); range.setEnd(node, Math.min(4, node.textContent.length));
      getSelection().removeAllRanges(); getSelection().addRange(range);
    });
    await admin.locator('.selpop:not([hidden]) [data-pop=ann]').click();
    await admin.locator('.ann-card textarea').fill('建议补充可量化的项目成果。');
    await admin.locator('.f[data-path="sections.1.items.0.bullets.0"]').evaluate(el => {
      el.focus();
      const node = document.createTreeWalker(el, NodeFilter.SHOW_TEXT).nextNode();
      const range = document.createRange(); range.setStart(node, 0); range.setEnd(node, Math.min(4, node.textContent.length));
      getSelection().removeAllRanges(); getSelection().addRange(range);
    });
    await admin.locator('.selpop:not([hidden]) [data-pop=ann]').click();
    await admin.locator('.ann-card.active textarea').fill('这一处需要补充技术方案。');
    await admin.locator('#shareBtn').click();
    await admin.locator('#sharePassword').fill('browser-guest-password');
    await admin.locator('#shareDialog button[type=submit]').click();
    await admin.getByText('分享已开启，查看密码已保存。请记录密码并交给本人。', { exact: true }).waitFor();
    await admin.locator('#shareDialog [data-close]').click();
    await admin.reload();
    await admin.locator('.a4 mark.ann').first().waitFor();
    assert.equal(await admin.locator('.ann-card textarea').first().inputValue(), '建议补充可量化的项目成果。');
    await admin.screenshot({ animations: 'disabled', path: path.join(output, 'admin-editor.png') });
    await admin.getByRole('link', { name: '简历工坊首页' }).click();
    await admin.locator('[data-doc]').first().waitFor();
    await admin.screenshot({ animations: 'disabled', path: path.join(output, 'admin-workspace.png') });
    await admin.locator('#resumeSearch').fill('not-a-resume');
    await admin.locator('#searchEmpty').waitFor();
    assert.equal(await admin.locator('[data-doc]:visible').count(), 0);
    await admin.locator('#resumeSearch').fill('示例');
    assert.equal(await admin.locator('[data-doc]:visible').count(), 1);
    await admin.setViewportSize({ width: 390, height: 844 });
    await admin.screenshot({ animations: 'disabled', path: path.join(output, 'admin-workspace-mobile.png') });
    assert(await admin.locator('#uploadBtn').isVisible());
    await admin.setViewportSize({ width: 1480, height: 940 });
    await admin.locator('[data-doc]').first().click();
    await admin.locator('.a4 mark.ann').first().waitFor();

    await guest.goto(`${base}/#/doc/${did}`);
    await guest.locator('#unlockForm').waitFor();
    assert.equal(await guest.locator('.a4').count(), 0);
    await guest.locator('#viewPassword').fill('wrong-password');
    await guest.locator('#unlockForm button').click();
    await guest.getByText('查看密码错误或分享已关闭', { exact: true }).waitFor();
    await guest.locator('#viewPassword').fill('browser-guest-password');
    await guest.locator('#unlockForm button').click();
    await guest.locator('.a4 mark.ann').first().waitFor();
    assert.equal(await guest.locator('[contenteditable=true]').count(), 0);
    assert.equal(await guest.locator('.ann-card textarea, .ann-card .del, .ann-card .sw').count(), 0);
    assert.equal(await guest.locator('#shareBtn, [data-open-settings], #drop').count(), 0);
    assert.equal(await guest.locator('.annotation-note').first().innerText(), '建议补充可量化的项目成果。');
    await guest.locator('.a4 mark.ann').first().click();
    assert(await guest.locator('.ann-card').first().evaluate(el => el.classList.contains('active')));
    assert(!/\d{1,2}\/\d{1,2}|\d{2}:\d{2}/.test(await guest.locator('.panel-body').innerText()));
    assert.equal((await guest.request.put(`${base}/api/docs/${did}`, { data: { annotations: [] } })).status(), 403);
    assert.equal((await guest.request.get(`${base}/api/docs`)).status(), 403);
    await guest.screenshot({ animations: 'disabled', path: path.join(output, 'guest-desktop.png') });
    await guest.setViewportSize({ width: 390, height: 844 });
    await guest.waitForFunction(() => document.querySelector('.a4').getBoundingClientRect().width < innerWidth);
    assert.equal(await guest.locator('.annotation-sheet[open]').count(), 0);
    assert.equal(await guest.locator('.panel').isVisible(), false);
    await guest.locator('.a4 mark.ann').first().tap();
    await guest.locator('.annotation-sheet[open]').waitFor();
    assert.equal(await guest.locator('.ann-card:visible').count(), 1);
    assert.equal(await guest.locator('.annotation-note:visible').innerText(), '建议补充可量化的项目成果。');
    assert(!/\d{1,2}\/\d{1,2}|\d{2}:\d{2}/.test(await guest.locator('.annotation-sheet').innerText()));
    await guest.screenshot({ animations: 'disabled', path: path.join(output, 'guest-mobile.png') });
    await guest.getByRole('button', { name: '关闭批注', exact: true }).click();
    await guest.locator('.annotation-sheet').waitFor({ state: 'hidden' });
    await guest.locator('.a4 mark.ann').nth(1).tap();
    assert.equal(await guest.locator('.annotation-note:visible').innerText(), '这一处需要补充技术方案。');
    await guest.keyboard.press('Escape');
    await guest.locator('.annotation-sheet').waitFor({ state: 'hidden' });
    await guest.locator('#sourceBtn').click();
    await guest.locator('.annotation-sheet .src-img').first().waitFor();
    assert.equal(await guest.locator('#annotationSheetTitle').innerText(), '简历原件');
    await guest.getByRole('button', { name: '关闭批注', exact: true }).click();
    await guest.locator('.annotation-sheet').waitFor({ state: 'hidden' });
    await guest.locator('.a4 mark.ann').first().tap();
    assert.equal(await guest.locator('.annotation-note:visible').innerText(), '建议补充可量化的项目成果。');
    await guest.setViewportSize({ width: 1480, height: 940 });
    await guest.locator('.annotation-sheet').waitFor({ state: 'hidden' });
    assert.equal(await guest.locator('.editor > .panel').isVisible(), true);
    assert.equal(await guest.locator('.ann-card:visible').count(), 2);
    await guest.setViewportSize({ width: 390, height: 844 });
    await guest.locator('[data-logout]').click();
    await guest.locator('#unlockForm').waitFor();
    assert.equal(await guest.locator('.a4').count(), 0);
    await guest.goto(`${base}/#/`);
    await guest.locator('#viewPassword').fill('browser-guest-password');
    await guest.locator('#unlockForm button').click();
    await guest.locator('.a4 mark.ann').first().waitFor();
    assert.equal(await guest.locator('.annotation-sheet[open]').count(), 0);
    assert(guest.url().endsWith(`#/doc/${did}`));

    await admin.setViewportSize({ width: 390, height: 844 });
    await admin.locator('.a4 mark.ann').first().click();
    await admin.locator('.annotation-sheet[open] textarea:visible').fill('移动端保存的批注意见');
    await admin.getByRole('button', { name: '关闭批注', exact: true }).click();
    await admin.locator('#savestate').filter({ hasText: '已保存' }).waitFor();
    await admin.reload();
    await admin.locator('.a4 mark.ann').first().click();
    assert.equal(await admin.locator('.annotation-sheet textarea:visible').inputValue(), '移动端保存的批注意见');
    await admin.setViewportSize({ width: 1480, height: 940 });
    await admin.locator('.annotation-sheet').waitFor({ state: 'hidden' });
    await admin.locator('#shareBtn').click();
    await admin.locator('#sharePassword').fill('browser-replacement-password');
    await admin.locator('#shareDialog button[type=submit]').click();
    await admin.getByText('分享已开启，查看密码已保存。请记录密码并交给本人。', { exact: true }).waitFor();
    await guest.reload();
    await guest.locator('#unlockForm').waitFor();
    assert.equal((await guest.request.get(`${base}/api/docs/${did}`)).status(), 403);
    await admin.locator('.disable-share').click();
    await admin.locator('#shareDialog').waitFor({ state: 'hidden' });
    await admin.locator('[data-logout]').click();
    await admin.locator('#unlockForm').waitFor();
    assert.equal((await admin.request.get(`${base}/api/docs/${did}`)).status(), 403);
    assert.deepEqual(errors, []);
    console.log('UI PASS: admin upload/edit/annotate/share; guest password-only and link unlock/read-only; mobile annotations; password rotation; logout.');
    console.log(`Screenshots: ${output}`);
  } finally {
    // Remove only the demo created by this walkthrough.
    if (did) {
      await admin.request.post(`${base}/api/auth/login`, { data: { password } });
      await admin.request.delete(`${base}/api/docs/${did}`);
    }
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
